func New(ctx context.Context, options Options) (_ *Application, returned error) {
	if err := validateServiceRPCOptions(options); err != nil {
		return nil, err
	}
	if err := normalizeShutdownOptions(&options); err != nil {
		return nil, err
	}
	if options.OperatorCredentialPath != "" {
		parent, err := filepath.Abs(filepath.Dir(options.OperatorCredentialPath))
		if err != nil {
			return nil, ErrOperatorCredential
		}
		stage, err := filepath.Abs(filepath.Join(options.DataDirectory, "runtime", "platform"))
		if err != nil {
			return nil, ErrOperatorCredential
		}
		// Reject a credential placed in the publication-temp namespace before
		// opening files or running crash recovery: it must never be mistaken
		// for an abandoned temporary file and removed.
		if parent == stage && strings.HasPrefix(filepath.Base(options.OperatorCredentialPath), "publish-") {
			return nil, ErrOperatorCredential
		}
	}
	if options.Initialization.Administrator != nil {
		admin := options.Initialization.Administrator
		if err := identity.ValidatePassword(admin.Password); err != nil {
			return nil, err
		}
		if !regexpAccount(admin.Account) {
			return nil, contracts.NewError("INVALID_REQUEST", "account")
		}
	}
	if options.Initialization.Runtime != nil {
		if err := ValidateRuntime(*options.Initialization.Runtime); err != nil {
			return nil, err
		}
	}
	storeOptions := corestore.Options{Directory: options.DataDirectory}
	if options.OperatorCredentialPath != "" {
		parent, err := filepath.Abs(filepath.Dir(options.OperatorCredentialPath))
		if err != nil {
			return nil, corestore.ErrStorage
		}
		directory, err := filepath.Abs(options.DataDirectory)
		if err != nil {
			return nil, corestore.ErrStorage
		}
		if parent == directory {
			storeOptions.OperatorCredentialName = filepath.Base(options.OperatorCredentialPath)
		}
	}
	store, err := corestore.Open(ctx, storeOptions)
	if err != nil {
		return nil, err
	}
	// The log facility starts after the installation lock and before identity
	// recovery or listeners. A failure here leaves the data directory untouched
	// beyond this feature's own namespace.
	if err := store.RecoverLogStorage(); err != nil {
		store.Close()
		return nil, err
	}
	logsRoot, err := store.OpenCoreLogDir()
	if err != nil {
		store.Close()
		return nil, err
	}
	logs, err := corelogs.Open(logsRoot, corelogs.Options{Stdout: options.Stdout, Stderr: options.Stderr})
	if err != nil {
		logsRoot.Close()
		store.Close()
		return nil, err
	}
	abortLogs := func() {
		_ = logs.Close()
		logsRoot.Close()
		store.Close()
	}
	files, err := store.OpenPlatformFiles()
	if err != nil {
		abortLogs()
		return nil, err
	}
	settings := NewSettings(store, files)
	if err := files.SetOperatorPath(options.OperatorCredentialPath); err != nil {
		files.Close()
		abortLogs()
		return nil, ErrOperatorCredential
	}
	if err := settings.EnsureOperator(ctx); err != nil {
		files.Close()
		abortLogs()
		return nil, err
	}
	id, err := identity.New(ctx, store, identity.Options{})
	if err != nil {
		files.Close()
		abortLogs()
		return nil, err
	}
	keep := false
	defer func() {
		if !keep {
			id.Close()
			files.Close()
			_ = logs.Close()
			logsRoot.Close()
			store.Close()
		}
	}()
	hasUsers, err := id.HasUsers(ctx)
	if err != nil {
		return nil, err
	}
	if !hasUsers && options.Initialization.Administrator != nil {
		admin := options.Initialization.Administrator
		if _, err := id.Bootstrap(ctx, admin.Account, admin.Password); err != nil {
			return nil, err
		}
	}
	_, configured, err := settings.LoadRuntime()
	if err != nil {
		return nil, err
	}
	if !configured && options.Initialization.Runtime != nil {
		if _, err := settings.ConfigureRuntime(*options.Initialization.Runtime); err != nil {
			return nil, err
		}
	}
	root, err := files.OpenInspectionRoot()
	if err != nil {
		return nil, err
	}
	lifetime, cancel := context.WithCancel(context.Background())
	a := &Application{Store: store, Identity: id, Settings: settings, files: files, inspectionRoot: root, logs: logs, logsRoot: logsRoot, options: options, ctx: lifetime, cancel: cancel, state: "STORE_OPEN", refresh: make(chan struct{}, 1), serveDone: make(chan error, 2)}
	a.serviceGateway = newServiceGateway(a)
	a.packageSlots = make(chan struct{}, 2)
	a.archiveSlots = make(chan struct{}, 2)
	a.logUserDownloads = map[string]int{}
	a.logExportsDownloading = map[string]int{}
	a.environmentSlots = make(chan struct{}, 2)
	a.environmentCache = preparationcache.New[environmentKey](lifetime, preparationcache.Options[contracts.PiPackagePreparedEnvironment]{Phase: "environment-probe", Clone: cloneEnvironment})
	a.preparation = newRuntimePreparation(a)
	if err := store.Write(ctx, func(tx *sql.Tx) error {
		var err error
		a.fileEpoch, err = corestore.NextFileCoreEpoch(tx)
		return err
	}); err != nil {
		root.Close()
		cancel()
		return nil, err
	}
	// A crash after publishing bytes but before committing the catalog can
	// leave an unreferenced digest or staging directory. Reclaim it before
	// this Core accepts another Skill operation.
	if err := skillartifact.CleanupOrphans(store); err != nil {
		root.Close()
		cancel()
		return nil, err
	}
	if err := store.Write(ctx, corestore.RecoverContextPackageLeases); err != nil {
		root.Close()
		cancel()
		return nil, err
	}
	if err := a.recoverPackageUploadFiles(ctx); err != nil {
		root.Close()
		cancel()
		return nil, err
	}
	// Model management is available before Runtime is configured. Migrate its
	// registry independently of runtime catalog/default initialization.
	if err := a.adoptRuntimeModels(ctx); err != nil {
		root.Close()
		cancel()
		return nil, err
	}
	a.status.Checks.FilesystemMigrationReady = true
	if err := a.recoverDiagnosticAttempts(ctx); err != nil {
		root.Close()
		cancel()
		return nil, err
	}
	a.recoverLogExports(ctx)
	a.startLogExportGC()
	keep = true
	a.attachStandardLog()
	a.startPackageUploadCollector()
	return a, nil
}
func regexpAccount(s string) bool {
	if len(s) < 1 || len(s) > 128 {
		return false
	}
	for i, c := range s {
		if (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') {
			continue
		}
		if i == 0 || !strings.ContainsRune("._:-", c) {
			return false
		}
	}
	return true
}

// Listen is the standalone Core startup convenience. The unified composition
// root binds both services before calling Serve, so recovery cannot start in a
// partially bound installation.
func (a *Application) Listen(address ListenAddress) (ListenAddress, error) {
	bound, err := a.Bind(address)
	if err != nil {
		return ListenAddress{}, err
	}
	if err := a.Serve(); err != nil {
		return ListenAddress{}, err
	}
	return bound, nil
}

func (a *Application) Bind(address ListenAddress) (ListenAddress, error) {
	a.mu.Lock()
	defer a.mu.Unlock()
	if a.closed || a.server != nil {
		return ListenAddress{}, errors.New("Core application cannot listen twice")
	}
	bindHost := address.Host
	if strings.EqualFold(bindHost, "localhost") {
		bindHost = "127.0.0.1"
	}
	network := "tcp"
	if ip := net.ParseIP(bindHost); ip != nil && ip.To4() != nil {
		network = "tcp4"
	}
	listener, err := net.Listen(network, net.JoinHostPort(bindHost, stringsPort(address.Port)))
	if err != nil {
		return ListenAddress{}, errors.New("Core HTTP listener is unavailable")
	}
	a.listener = listener
	a.server = &http.Server{Handler: http.HandlerFunc(a.route), ReadHeaderTimeout: 10 * time.Second, ReadTimeout: 31 * time.Minute, IdleTimeout: 90 * time.Second, MaxHeaderBytes: 32 << 10, BaseContext: func(net.Listener) context.Context { return a.ctx }}
	actual := listener.Addr().(*net.TCPAddr)
	return ListenAddress{actual.IP.String(), actual.Port}, nil
}

func (a *Application) Serve() error {
	a.mu.Lock()
	if a.closed || a.server == nil || a.serving {
		a.mu.Unlock()
		return errors.New("Core listener is not available")
	}
	a.serving = true
	a.state = "LISTENING"
	server, listener := a.server, a.listener
	a.mu.Unlock()
	go func() {
		err := server.Serve(listener)
		if errors.Is(err, http.ErrServerClosed) {
			err = nil
		}
		a.serveDone <- err
	}()
	if err := a.ScheduleRuntimeRefresh(); err != nil {
		a.setState("RUNTIME_UNAVAILABLE", true, false, false)
	}
	return nil
}

// ServeDone reports an unexpected listener exit to the single startup owner.
func (a *Application) ServeDone() <-chan error { return a.serveDone }
func stringsPort(port int) string              { return strconv.Itoa(port) }
func (a *Application) setState(state string, admin, configured, available bool) {
	a.mu.Lock()
	defer a.mu.Unlock()
	if a.closed {
		return
	}
	a.state = state
	a.status = Status{State: state, Ready: state == "READY"}
	a.status.Checks.Administrator = admin
	a.status.Checks.RuntimeConfigured = configured
	a.status.Checks.RuntimeAvailable = available
	a.status.Checks.FilesystemMigrationReady = true
}
func (a *Application) Status() Status {
	a.mu.Lock()
	defer a.mu.Unlock()
	return a.statusLocked()
}
func (a *Application) statusLocked() Status {
	status := a.status
	status.State = a.state
	status.Ready = a.state == "READY"
	return status
}

func (a *Application) deliveryStatus() (Status, Preparation) {
	a.mu.Lock()
	defer a.mu.Unlock()
	return a.statusLocked(), a.preparationLocked()
}

var errRecoveryRequired = errors.New("startup recovery handlers are required")

func (a *Application) RefreshRuntime(request context.Context) error {
	// Retained for in-process callers which explicitly need an observation
	// barrier. Production startup and HTTP handlers only schedule preparation.
	if err := a.ScheduleRuntimeRefresh(); err != nil {
		return err
	}
	return a.preparation.waitForBase(request)
}
func (a *Application) initializeDocker(ctx context.Context) error {
	if a.engine == nil {
		endpoint, err := dockerengine.SelectEndpoint(a.options.DockerOptions)
		if err != nil {
			return err
		}
		engine, err := dockerengine.Connect(ctx, endpoint)
		if err != nil {
			return err
		}
		inspector, err := dockerengine.NewImageInspectorWithLifecycle(ctx, a.ctx, engine, a.inspectionRoot, a.Store)
		if err != nil {
			engine.Close()
			return err
		}
		a.mu.Lock()
		if a.closed || ctx.Err() != nil {
			a.mu.Unlock()
			engine.Close()
			return context.Canceled
		}
		a.engine, a.inspector = engine, inspector
		a.mu.Unlock()
	}
	if err := a.engine.Ping(ctx); err != nil {
		return err
	}
	if a.workRuntime == nil {
		resources, err := dockerengine.NewRuntime(a.engine, a.Store.InstallationID(), func(ctx context.Context, plan dockerengine.ResourcePlan) error {
			return a.Store.RecordResourceIntent(ctx, corestore.ResourceIntent{WorkID: plan.WorkID, Kind: plan.Kind, LogicalID: plan.LogicalID, Name: plan.Name, Labels: plan.Labels})
		}, []string{a.options.DataDirectory})
		if err != nil {
			return err
		}
		resources.SetPackageSettler(func(ctx context.Context, plan dockerengine.ResourcePlan) error {
			return a.Store.SettlePackageCreation(ctx, plan.WorkID, plan.Kind, plan.LogicalID, plan.Name)
		})
		manager := a.agentTLS
		if manager == nil {
			manager, err = internaltls.Open(filepath.Join(a.options.DataDirectory, "runtime", "agent-tls"), a.Store)
		}
		if err != nil {
			return err
		}
		a.mu.Lock()
		if a.closed || ctx.Err() != nil {
			a.mu.Unlock()
			manager.Close()
			return context.Canceled
		}
		a.dockerRuntime, a.agentTLS = resources, manager
		a.workRuntime = &workruntime.Runtime{Docker: resources, Inspector: a.inspector, TLS: manager}
		a.mu.Unlock()
	}
	return a.listenServiceRPC(ctx)
}
func (a *Application) emptyRecovery(ctx context.Context) error {
	// This guard keeps staged implementation honest. Actual durable workload
	// recovery is implemented by tasks 5/6/8/9, not a no-op startup hook.
	var n int
	err := a.Store.Read(ctx, func(tx *sql.Tx) error {
		return tx.QueryRowContext(ctx, `SELECT (SELECT count(*) FROM works)+(SELECT count(*) FROM pi_package_jobs)+(SELECT count(*) FROM work_file_jobs)+(SELECT count(*) FROM snapshot_jobs)`).Scan(&n)
	})
	if err != nil {
		return err
	}
	if n != 0 {
		return errRecoveryRequired
	}
	return nil
}
func (a *Application) Close(ctx context.Context) error {
	a.shutdownMu.Lock()
	defer a.shutdownMu.Unlock()
	ctx, cancel := context.WithTimeout(ctx, a.options.ShutdownTimeout)
	defer cancel()
	a.mu.Lock()
	if a.shutdownComplete {
		a.mu.Unlock()
		return nil
	}
	a.closed = true
	a.state = "SHUTTING_DOWN"
	server := a.server
	serviceServer := a.serviceServer
	a.mu.Unlock()
	a.workQueueMu.Lock()
	a.cancel()
	a.workQueueMu.Unlock()
	a.Identity.Close()
	// Work shutdown has its own fencing and per-Work locks. Start it after
	// admission is closed and coordination is cancelled, while the total
	// process budget is still available. A stalled control request or worker
	// must not consume that budget before any managed runtime is stopped.
	workloadsDone := make(chan error, 1)
	go func() {
		if a.options.Shutdown != nil {
			workloadsDone <- a.options.Shutdown(ctx, a)
		} else {
			workloadsDone <- a.shutdownCapturedWorks(ctx)
		}
	}()
	var result error
	controlContext, stopControl := context.WithTimeout(ctx, a.options.WorkDrainTimeout)
	if serviceServer != nil {
		stopped := make(chan struct{})
		go func() { serviceServer.GracefulStop(); close(stopped) }()
		select {
		case <-stopped:
		case <-controlContext.Done():
			serviceServer.Stop()
			result = errors.New("Core service control shutdown was not confirmed")
		}
	}
	if server != nil {
		err := server.Shutdown(controlContext)
		if err != nil {
			server.Close()
			result = errors.New("Core HTTP shutdown was not confirmed")
		}
	}
	if a.listener != nil {
		_ = a.listener.Close()
	}
	stopControl()
	finished := make(chan struct{})
	go func() { a.refreshWG.Wait(); close(finished) }()
	select {
	case <-finished:
	case <-ctx.Done():
		result = errors.New("Core runtime shutdown was not confirmed")
	}
	workersDone := make(chan struct{})
	go func() {
		a.workWG.Wait()
		a.packageWG.Wait()
		a.fileWG.Wait()
		a.snapshotWG.Wait()
		a.logExportWG.Wait()
		close(workersDone)
	}()
	select {
	case <-workersDone:
	case <-ctx.Done():
		result = errors.New("Core Work coordination did not stop")
	}
	recoveryDone := make(chan struct{})
	go func() { a.recoveryWG.Wait(); close(recoveryDone) }()
	select {
	case <-recoveryDone:
	case <-ctx.Done():
		result = errors.New("Core recovery coordination did not stop")
	}
	select {
	case err := <-workloadsDone:
		if err != nil {
			result = errors.New("Core workload shutdown was not confirmed")
		}
	case <-ctx.Done():
		result = errors.New("Core workload shutdown was not confirmed")
	}
	if a.environmentCache != nil {
		if err := a.environmentCache.Close(ctx); err != nil {
			_ = a.shutdownLogs(errors.New("Core shared environment preparation shutdown was not confirmed"))
			return errors.New("Core shared environment preparation shutdown was not confirmed")
		}
	}
	if a.inspector != nil {
		if err := a.inspector.Close(ctx); err != nil {
			if a.inspector.InspectionsActive() {
				_ = a.shutdownLogs(errors.New("Core shared image inspection shutdown was not confirmed"))
				return errors.New("Core shared image inspection shutdown was not confirmed")
			}
			result = errors.New("Core shared image inspection cleanup was not confirmed")
		}
	}
	if err := a.closeEnvironmentProbes(ctx); err != nil {
		result = err
	}
	if a.engine != nil {
		a.engine.Close()
	}
	if a.agentTLS != nil {
		a.agentTLS.Close()
	}
	a.inspectionRoot.Close()
	if err := a.shutdownLogs(result); err != nil {
		result = err
	}
	a.files.Close()
	if err := a.Store.Close(); err != nil {
		result = errors.New("Core storage shutdown was not confirmed")
	}
	a.mu.Lock()
	a.shutdownComplete = true
	a.mu.Unlock()
	return result
}

func send(w http.ResponseWriter, status int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	w.WriteHeader(status)
	json.NewEncoder(w).Encode(value)
}
func (a *Application) route(w http.ResponseWriter, r *http.Request) {
	trace := &operationTrace{app: a, correlation: string(requestCorrelation()), preacceptDiagnostics: diagnostics.Empty()}
	tracedRequest := context.WithValue(r.Context(), traceKey{}, trace)
	if diagnostics.PerformanceWriter(tracedRequest) == nil {
		tracedRequest = diagnostics.WithPerformanceWriter(tracedRequest, a.consoleStderr())
	}
	tracedRequest = diagnostics.WithPerformanceSink(tracedRequest, a.diagnosticSink())
	r = r.WithContext(diagnostics.WithPerformance(tracedRequest, diagnostics.PerformanceIdentity{CorrelationID: trace.correlation}))
	var requestSpan *diagnostics.PerformanceSpan
	var requestErr error
	if r.Method == http.MethodPost && r.URL.EscapedPath() == "/api/v1/works" {
		requestSpan = diagnostics.BeginPerformance(r.Context(), "create-request")
	}
	defer func() { requestSpan.End(requestErr) }()
	defer func() {
		if failure := recover(); failure != nil {
			if failure == http.ErrAbortHandler {
				panic(failure)
			}
			requestErr = contracts.NewError("INTERNAL_ERROR", "")
			contracts.WriteError(w, contracts.NewError("INTERNAL_ERROR", ""))
		}
	}()
	if workfiles.IsRawTarget(r.RequestURI) {
		a.serveFiles(w, r)
		return
	}
	if err := a.handle(w, r); err != nil {
		requestErr = err
		if strings.HasPrefix(r.URL.Path, "/api/v1/admin/") {
			status, view := contracts.ProjectAdminError(err, requestCorrelation())
			send(w, status, view)
		} else {
			if trace.preacceptFailed {
				status, view := contracts.ProjectError(err)
				raw, _ := json.Marshal(view)
				var body map[string]any
				_ = json.Unmarshal(raw, &body)
				body["correlationId"] = trace.correlation
				send(w, status, body)
			} else {
				contracts.WriteError(w, err)
			}
		}
	}
}
